def render_inputs(calls):
    """역할·정답을 모델 입력에서 제거하며 A/B의 역할 대응도 통화마다 바꾼다."""
    result = []
    for index, call in enumerate(calls):
        mapping = {"나": "A", "피싱범": "B"} if index % 2 == 0 else {"나": "B", "피싱범": "A"}
        result.append({
            "call_id": call["call_id"],
            "utterances": [
                {"sentence_id": u["sentence_id"], "speaker": mapping[u["speaker"]], "text": u["text"]}
                for u in call["utterances"]
            ],
        })
    return {"schema_version": "1.0", "calls": result}


def object_form(word):
    """합성 사례 제목 뒤의 목적격 조사만 맞춘다."""
    return word + ("을" if (ord(word[-1]) - ord("가")) % 28 else "를")


